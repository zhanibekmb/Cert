export function t(str, vars) {
  let out = _lang === "ru" ? (RU[str] || str) : str;
  if (vars) for (const k in vars) out = out.split("{" + k + "}").join(String(vars[k]));
  return out;
}

export function getLangPref() { return _pref; }
export function activeLang() { return _lang; }

export function setLangPref(pref) {
  _pref = pref === "ru" || pref === "en" ? pref : "system";
  _lang = _pref === "system" ? deviceLang() : _pref;
  AsyncStorage.setItem("cert_lang", _pref).catch(() => {});
  _listeners.forEach((fn) => fn());
}

export async function initLang() {
  try { const p = await AsyncStorage.getItem("cert_lang"); if (p) setLangPref(p); } catch (_) { /* ignore */ }
}

// Subscribe a component (use at the root) so a language change re-renders the tree.
export function useLang() {
  const [, force] = useState(0);
  useEffect(() => { const fn = () => force((x) => x + 1); _listeners.add(fn); return () => _listeners.delete(fn); }, []);
  return [_pref, setLangPref];
}
